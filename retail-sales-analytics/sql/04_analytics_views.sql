-- 04_analytics_views.sql
-- Reusable analytics views. All business formulas live in V_SALES_OVERVIEW so
-- every other view (and the app) uses one consistent definition.
--
-- Definitions (INR):
--   gross_sales          = unit_price_inr * quantity
--   discount             = discount_amount_inr
--   revenue_before_ret.  = revenue_inr                 (gross - discount)
--   net_revenue          = net_revenue_inr             (revenue - return_amount)
--   contribution (est.)  = net_revenue - COGS - shipping - marketing
--   margin %             = contribution / net_revenue * 100   (NULL when net_revenue = 0)
--   AOV                  = net_revenue / distinct transaction_id
--   return rate %        = returned txns / distinct txns * 100
-- Returns: the data fully reverses revenue (return_amount = revenue) while COGS,
-- shipping and marketing remain charged, i.e. no inventory recovery is credited
-- and no extra handling cost is recorded. Contribution is therefore conservative.
USE ROLE RETAIL_ANALYST;
USE WAREHOUSE RETAIL_WH;
USE SCHEMA RETAIL_ANALYTICS.SALES;

CREATE OR REPLACE VIEW V_SALES_OVERVIEW COMMENT = 'Transaction-level enriched sales with standard business measures' AS
SELECT
  t.TRANSACTION_ID, t.TRANSACTION_DATE,
  DATE_TRUNC('MONTH', t.TRANSACTION_DATE)::DATE                         AS SALE_MONTH,
  t.PRODUCT_NAME, t.CATEGORY, t.REGION, t.SALES_CHANNEL, t.CUSTOMER_SEGMENT,
  t.PAYMENT_METHOD,
  IFF(t.PROMOTION_TYPE IS NULL OR t.PROMOTION_TYPE = 'None', 'No Promotion', t.PROMOTION_TYPE) AS PROMOTION_TYPE,
  t.QUANTITY, t.UNIT_PRICE_INR, t.DISCOUNT_PCT,
  t.UNIT_PRICE_INR * t.QUANTITY                                         AS GROSS_SALES_INR,
  t.DISCOUNT_AMOUNT_INR, t.REVENUE_INR, t.RETURNED, t.RETURN_AMOUNT_INR, t.NET_REVENUE_INR,
  t.COST_OF_GOODS_INR, t.SHIPPING_COST_INR, t.MARKETING_COST_INR,
  t.NET_REVENUE_INR - t.COST_OF_GOODS_INR - t.SHIPPING_COST_INR - t.MARKETING_COST_INR AS CONTRIBUTION_INR,
  t.NET_PROFIT_INR                                                      AS RECORDED_NET_PROFIT_INR,
  COUNT(*) OVER (PARTITION BY t.TRANSACTION_ID) > 1                     AS IS_DUPLICATE_ID,
  t.UPLOAD_ID
FROM SALES_TRANSACTIONS t;

CREATE OR REPLACE VIEW V_MONTHLY_SALES AS
SELECT SALE_MONTH,
  COUNT(DISTINCT TRANSACTION_ID)                  AS TXN_COUNT,
  SUM(QUANTITY)                                   AS UNITS,
  SUM(GROSS_SALES_INR)                            AS GROSS_SALES_INR,
  SUM(DISCOUNT_AMOUNT_INR)                        AS DISCOUNT_INR,
  SUM(REVENUE_INR)                                AS REVENUE_INR,
  SUM(RETURN_AMOUNT_INR)                          AS RETURNS_INR,
  SUM(NET_REVENUE_INR)                            AS NET_REVENUE_INR,
  SUM(COST_OF_GOODS_INR)                          AS COGS_INR,
  SUM(SHIPPING_COST_INR)                          AS SHIPPING_INR,
  SUM(MARKETING_COST_INR)                         AS MARKETING_INR,
  SUM(CONTRIBUTION_INR)                           AS CONTRIBUTION_INR,
  DIV0NULL(SUM(CONTRIBUTION_INR), SUM(NET_REVENUE_INR)) * 100          AS MARGIN_PCT,
  DIV0NULL(SUM(NET_REVENUE_INR), COUNT(DISTINCT TRANSACTION_ID))      AS AOV_INR,
  DIV0NULL(COUNT(DISTINCT IFF(RETURNED, TRANSACTION_ID, NULL)), COUNT(DISTINCT TRANSACTION_ID)) * 100 AS RETURN_RATE_PCT
FROM V_SALES_OVERVIEW
GROUP BY SALE_MONTH;

CREATE OR REPLACE VIEW V_CATEGORY_PROFITABILITY AS
SELECT CATEGORY,
  COUNT(DISTINCT TRANSACTION_ID) AS TXN_COUNT, SUM(QUANTITY) AS UNITS,
  SUM(GROSS_SALES_INR) AS GROSS_SALES_INR, SUM(DISCOUNT_AMOUNT_INR) AS DISCOUNT_INR,
  SUM(NET_REVENUE_INR) AS NET_REVENUE_INR, SUM(COST_OF_GOODS_INR) AS COGS_INR,
  SUM(SHIPPING_COST_INR) AS SHIPPING_INR, SUM(MARKETING_COST_INR) AS MARKETING_INR,
  SUM(CONTRIBUTION_INR) AS CONTRIBUTION_INR,
  DIV0NULL(SUM(CONTRIBUTION_INR), SUM(NET_REVENUE_INR)) * 100 AS MARGIN_PCT,
  DIV0NULL(COUNT(DISTINCT IFF(RETURNED, TRANSACTION_ID, NULL)), COUNT(DISTINCT TRANSACTION_ID)) * 100 AS RETURN_RATE_PCT,
  RATIO_TO_REPORT(SUM(NET_REVENUE_INR)) OVER () * 100 AS REVENUE_SHARE_PCT
FROM V_SALES_OVERVIEW GROUP BY CATEGORY;

CREATE OR REPLACE VIEW V_REGIONAL_PERFORMANCE AS
SELECT REGION, SALES_CHANNEL,
  COUNT(DISTINCT TRANSACTION_ID) AS TXN_COUNT, SUM(QUANTITY) AS UNITS,
  SUM(NET_REVENUE_INR) AS NET_REVENUE_INR, SUM(CONTRIBUTION_INR) AS CONTRIBUTION_INR,
  DIV0NULL(SUM(CONTRIBUTION_INR), SUM(NET_REVENUE_INR)) * 100 AS MARGIN_PCT,
  DIV0NULL(SUM(NET_REVENUE_INR), COUNT(DISTINCT TRANSACTION_ID)) AS AOV_INR,
  DIV0NULL(COUNT(DISTINCT IFF(RETURNED, TRANSACTION_ID, NULL)), COUNT(DISTINCT TRANSACTION_ID)) * 100 AS RETURN_RATE_PCT,
  DIV0NULL(SUM(DISCOUNT_AMOUNT_INR), SUM(GROSS_SALES_INR)) * 100 AS EFFECTIVE_DISCOUNT_PCT
FROM V_SALES_OVERVIEW GROUP BY REGION, SALES_CHANNEL;

CREATE OR REPLACE VIEW V_PRODUCT_PERFORMANCE AS
SELECT PRODUCT_NAME, CATEGORY,
  COUNT(DISTINCT TRANSACTION_ID) AS TXN_COUNT, SUM(QUANTITY) AS UNITS,
  DIV0NULL(SUM(REVENUE_INR), SUM(QUANTITY)) AS AVG_SELLING_PRICE_INR,
  SUM(GROSS_SALES_INR) AS GROSS_SALES_INR, SUM(DISCOUNT_AMOUNT_INR) AS DISCOUNT_INR,
  SUM(NET_REVENUE_INR) AS NET_REVENUE_INR, SUM(COST_OF_GOODS_INR) AS COGS_INR,
  SUM(CONTRIBUTION_INR) AS CONTRIBUTION_INR,
  DIV0NULL(SUM(CONTRIBUTION_INR), SUM(NET_REVENUE_INR)) * 100 AS MARGIN_PCT,
  DIV0NULL(COUNT(DISTINCT IFF(RETURNED, TRANSACTION_ID, NULL)), COUNT(DISTINCT TRANSACTION_ID)) * 100 AS RETURN_RATE_PCT,
  -- return rate H2 vs H1 (trend signal)
  DIV0NULL(COUNT(DISTINCT IFF(RETURNED AND MONTH(TRANSACTION_DATE) > 6, TRANSACTION_ID, NULL)), COUNT(DISTINCT IFF(MONTH(TRANSACTION_DATE) > 6, TRANSACTION_ID, NULL))) * 100
  - DIV0NULL(COUNT(DISTINCT IFF(RETURNED AND MONTH(TRANSACTION_DATE) <= 6, TRANSACTION_ID, NULL)), COUNT(DISTINCT IFF(MONTH(TRANSACTION_DATE) <= 6, TRANSACTION_ID, NULL))) * 100
    AS RETURN_RATE_CHANGE_H2_VS_H1_PP
FROM V_SALES_OVERVIEW GROUP BY PRODUCT_NAME, CATEGORY;

-- Long format: one row per (dimension, value) so returns can be compared across dimensions
CREATE OR REPLACE VIEW V_RETURN_ANALYSIS AS
WITH b AS (SELECT * FROM V_SALES_OVERVIEW),
u AS (
  SELECT 'PRODUCT' DIM, PRODUCT_NAME VAL, * EXCLUDE (PRODUCT_NAME) FROM b
  UNION ALL SELECT 'CATEGORY', CATEGORY, * EXCLUDE (CATEGORY) FROM b
  UNION ALL SELECT 'REGION', REGION, * EXCLUDE (REGION) FROM b
  UNION ALL SELECT 'SALES_CHANNEL', SALES_CHANNEL, * EXCLUDE (SALES_CHANNEL) FROM b
)
SELECT DIM AS DIMENSION, VAL AS DIMENSION_VALUE,
  COUNT(DISTINCT TRANSACTION_ID) AS TXN_COUNT,
  COUNT(DISTINCT IFF(RETURNED, TRANSACTION_ID, NULL)) AS RETURNED_TXNS,
  DIV0NULL(COUNT(DISTINCT IFF(RETURNED, TRANSACTION_ID, NULL)), COUNT(DISTINCT TRANSACTION_ID)) * 100 AS RETURN_RATE_PCT,
  SUM(RETURN_AMOUNT_INR) AS RETURNED_REVENUE_INR,
  SUM(IFF(RETURNED, CONTRIBUTION_INR, 0)) AS CONTRIBUTION_LOSS_ON_RETURNS_INR
FROM u GROUP BY DIM, VAL;

CREATE OR REPLACE VIEW V_PROMOTION_ANALYSIS AS
SELECT PROMOTION_TYPE,
  COUNT(DISTINCT TRANSACTION_ID) AS TXN_COUNT, SUM(QUANTITY) AS UNITS,
  AVG(DISCOUNT_PCT) AS AVG_DISCOUNT_PCT,
  SUM(DISCOUNT_AMOUNT_INR) AS DISCOUNT_INR,
  SUM(NET_REVENUE_INR) AS NET_REVENUE_INR, SUM(CONTRIBUTION_INR) AS CONTRIBUTION_INR,
  SUM(MARKETING_COST_INR) AS MARKETING_INR,
  DIV0NULL(SUM(CONTRIBUTION_INR), SUM(NET_REVENUE_INR)) * 100 AS MARGIN_PCT,
  DIV0NULL(SUM(NET_REVENUE_INR), COUNT(DISTINCT TRANSACTION_ID)) AS AOV_INR,
  DIV0NULL(SUM(QUANTITY), COUNT(DISTINCT TRANSACTION_ID)) AS UNITS_PER_TXN,
  DIV0NULL(COUNT(DISTINCT IFF(RETURNED, TRANSACTION_ID, NULL)), COUNT(DISTINCT TRANSACTION_ID)) * 100 AS RETURN_RATE_PCT
FROM V_SALES_OVERVIEW GROUP BY PROMOTION_TYPE;

-- Monthly driver table for forecasting & scenarios (complete month spine, no gaps)
CREATE OR REPLACE VIEW V_FORECAST_INPUTS AS
WITH bounds AS (SELECT MIN(SALE_MONTH) mn, MAX(SALE_MONTH) mx FROM V_SALES_OVERVIEW),
spine AS (
  SELECT DATEADD(MONTH, SEQ4(), (SELECT mn FROM bounds))::DATE AS SALE_MONTH
  FROM TABLE(GENERATOR(ROWCOUNT => 240))
  QUALIFY SALE_MONTH <= (SELECT mx FROM bounds)
)
SELECT s.SALE_MONTH,
  COALESCE(m.TXN_COUNT, 0) AS TXN_COUNT, COALESCE(m.UNITS, 0) AS UNITS,
  COALESCE(m.GROSS_SALES_INR, 0) AS GROSS_SALES_INR, COALESCE(m.DISCOUNT_INR, 0) AS DISCOUNT_INR,
  COALESCE(m.RETURNS_INR, 0) AS RETURNS_INR, COALESCE(m.NET_REVENUE_INR, 0) AS NET_REVENUE_INR,
  COALESCE(m.COGS_INR, 0) AS COGS_INR, COALESCE(m.SHIPPING_INR, 0) AS SHIPPING_INR,
  COALESCE(m.MARKETING_INR, 0) AS MARKETING_INR, COALESCE(m.CONTRIBUTION_INR, 0) AS CONTRIBUTION_INR,
  DIV0NULL(m.GROSS_SALES_INR, m.UNITS) AS AVG_LIST_PRICE_INR,
  DIV0NULL(m.DISCOUNT_INR, m.GROSS_SALES_INR) AS DISCOUNT_RATE,
  DIV0NULL(m.RETURNS_INR, m.REVENUE_INR) AS RETURN_VALUE_RATE,
  DIV0NULL(m.COGS_INR, m.GROSS_SALES_INR) AS COGS_TO_GROSS_RATIO,
  m.TXN_COUNT IS NULL AS IS_GAP_MONTH
FROM spine s LEFT JOIN V_MONTHLY_SALES m USING (SALE_MONTH);

-- Rule-based, evidence-backed findings computed purely from data.
-- Impact estimates are simple, documented what-ifs (not causal claims).
CREATE OR REPLACE VIEW V_BUSINESS_RECOMMENDATIONS AS
WITH tot AS (
  SELECT SUM(NET_REVENUE_INR) rev, SUM(CONTRIBUTION_INR) con, DIV0NULL(SUM(CONTRIBUTION_INR), SUM(NET_REVENUE_INR))*100 margin,
         DIV0NULL(COUNT_IF(RETURNED), COUNT(*))*100 rr
  FROM V_SALES_OVERVIEW),
prod AS (SELECT * FROM V_PRODUCT_PERFORMANCE),
low_margin AS (
  SELECT 'High revenue, low contribution margin' ISSUE, 'PRODUCT' DIMENSION, p.PRODUCT_NAME AFFECTED,
    'Revenue share ' || TO_VARCHAR(ROUND(p.NET_REVENUE_INR / t.rev * 100, 1)) || '%, margin ' || TO_VARCHAR(ROUND(p.MARGIN_PCT, 1)) || '% vs overall ' || TO_VARCHAR(ROUND(t.margin, 1)) || '%' EVIDENCE,
    p.MARGIN_PCT METRIC_VALUE, t.margin BENCHMARK,
    p.NET_REVENUE_INR * (t.margin - p.MARGIN_PCT) / 100 EST_IMPACT_INR,
    'Impact = revenue x gap to average margin (upper bound if margin reached average)' IMPACT_BASIS,
    'Review pricing, supplier cost and discount depth for this product' ACTION,
    'Product contribution margin %' KPI
  FROM prod p, tot t
  WHERE p.NET_REVENUE_INR >= (SELECT MEDIAN(NET_REVENUE_INR) FROM prod) AND p.MARGIN_PCT < t.margin - 2),
high_returns AS (
  SELECT 'High return rate', r.DIMENSION, r.DIMENSION_VALUE,
    'Return rate ' || TO_VARCHAR(ROUND(r.RETURN_RATE_PCT, 1)) || '% vs overall ' || TO_VARCHAR(ROUND(t.rr, 1)) || '% on ' || r.TXN_COUNT || ' txns',
    r.RETURN_RATE_PCT, t.rr,
    -r.CONTRIBUTION_LOSS_ON_RETURNS_INR * (r.RETURN_RATE_PCT - t.rr) / NULLIF(r.RETURN_RATE_PCT, 0),
    'Impact = contribution lost on returns x share of returns above the average rate',
    'Investigate product quality, descriptions and fulfilment for this segment',
    'Return rate %'
  FROM V_RETURN_ANALYSIS r, tot t
  WHERE r.DIMENSION IN ('PRODUCT', 'CATEGORY', 'REGION', 'SALES_CHANNEL') AND r.TXN_COUNT >= 30 AND r.RETURN_RATE_PCT > t.rr * 1.25),
promo AS (
  SELECT 'Promotion margin below no-promotion baseline', 'PROMOTION', p.PROMOTION_TYPE,
    'Margin ' || TO_VARCHAR(ROUND(p.MARGIN_PCT, 1)) || '% vs no-promotion ' || TO_VARCHAR(ROUND(b.MARGIN_PCT, 1)) || '%; avg discount ' || TO_VARCHAR(ROUND(p.AVG_DISCOUNT_PCT, 1)) || '%',
    p.MARGIN_PCT, b.MARGIN_PCT,
    p.NET_REVENUE_INR * (b.MARGIN_PCT - p.MARGIN_PCT) / 100,
    'Impact = promo revenue x margin gap vs no-promotion (ignores any incremental volume the promotion drove)',
    'Reduce discount depth or target the promotion to higher-margin products; A/B test',
    'Promotion margin % and incremental units'
  FROM V_PROMOTION_ANALYSIS p JOIN V_PROMOTION_ANALYSIS b ON b.PROMOTION_TYPE = 'No Promotion'
  WHERE p.PROMOTION_TYPE <> 'No Promotion' AND p.MARGIN_PCT < b.MARGIN_PCT - 2),
region AS (
  SELECT 'Regional margin gap', 'REGION', REGION,
    'Margin ' || TO_VARCHAR(ROUND(m, 1)) || '% vs overall ' || TO_VARCHAR(ROUND(t.margin, 1)) || '% on revenue ' || TO_VARCHAR(ROUND(r.region_rev, 0)),
    m, t.margin, r.region_rev * (t.margin - m) / 100,
    'Impact = regional revenue x gap to average margin',
    'Investigate regional discounting, shipping cost and return handling',
    'Regional contribution margin %'
  FROM (SELECT REGION, SUM(NET_REVENUE_INR) region_rev, DIV0NULL(SUM(CONTRIBUTION_INR), SUM(NET_REVENUE_INR))*100 m FROM V_SALES_OVERVIEW GROUP BY 1) r, tot t
  WHERE m < t.margin - 1.5),
unprofitable AS (
  SELECT 'Unprofitable transactions', 'TRANSACTION', 'All',
    COUNT(*) || ' transactions with negative contribution (' || COUNT_IF(RETURNED) || ' are returns); total loss ' || TO_VARCHAR(ROUND(-SUM(CONTRIBUTION_INR), 0)),
    COUNT(*), NULL, -SUM(IFF(NOT RETURNED, CONTRIBUTION_INR, 0)),
    'Impact = losses on non-returned negative-contribution transactions',
    'Set a minimum-margin floor on discounts and review fixed shipping on low-value orders',
    'Count of negative-contribution transactions'
  FROM V_SALES_OVERVIEW WHERE CONTRIBUTION_INR < 0 HAVING COUNT(*) > 0)
SELECT ROW_NUMBER() OVER (ORDER BY EST_IMPACT_INR DESC NULLS LAST) AS RANK, *
FROM (SELECT * FROM low_margin UNION ALL SELECT * FROM high_returns UNION ALL SELECT * FROM promo
      UNION ALL SELECT * FROM region UNION ALL SELECT * FROM unprofitable);
