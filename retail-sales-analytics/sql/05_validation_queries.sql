-- 05_validation_queries.sql
-- Data-quality checks. RUN_DATA_QUALITY_CHECKS() writes one row per check into
-- DATA_QUALITY_RESULTS (never modifies SALES_TRANSACTIONS). Safe to rerun.
USE ROLE RETAIL_ANALYST;
USE WAREHOUSE RETAIL_WH;
USE SCHEMA RETAIL_ANALYTICS.SALES;

CREATE OR REPLACE PROCEDURE RUN_DATA_QUALITY_CHECKS()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  run_id VARCHAR DEFAULT UUID_STRING();
BEGIN
  INSERT INTO DATA_QUALITY_RESULTS (CHECK_RUN_ID, TABLE_NAME, CHECK_NAME, SEVERITY, FAILED_ROWS, TOTAL_ROWS, STATUS, SAMPLE_IDS, DETAILS)
  WITH t AS (SELECT * FROM SALES_TRANSACTIONS),
  dup AS (SELECT TRANSACTION_ID FROM t GROUP BY 1 HAVING COUNT(*) > 1),
  checks AS (
    SELECT 'Duplicate transaction IDs' c, 'ERROR' s, (SELECT COUNT(*) FROM t WHERE TRANSACTION_ID IN (SELECT * FROM dup)) f,
           (SELECT ARRAY_AGG(TRANSACTION_ID) WITHIN GROUP (ORDER BY TRANSACTION_ID) FROM (SELECT * FROM dup LIMIT 20)) ids,
           'Rows sharing a transaction_id' d
    UNION ALL SELECT 'Missing required fields', 'ERROR',
           COUNT_IF(PRODUCT_NAME IS NULL OR CATEGORY IS NULL OR REGION IS NULL OR SALES_CHANNEL IS NULL OR CUSTOMER_SEGMENT IS NULL OR QUANTITY IS NULL OR NET_REVENUE_INR IS NULL OR COST_OF_GOODS_INR IS NULL),
           ARRAY_SLICE(ARRAY_AGG(IFF(PRODUCT_NAME IS NULL OR CATEGORY IS NULL OR REGION IS NULL OR QUANTITY IS NULL OR NET_REVENUE_INR IS NULL OR COST_OF_GOODS_INR IS NULL, TRANSACTION_ID, NULL)),0,20),
           'Null in a required dimension or measure' FROM t
    UNION ALL SELECT 'No-promotion rows (promotion_type NULL or ''None'')', 'INFO', COUNT_IF(PROMOTION_TYPE IS NULL OR PROMOTION_TYPE = 'None'), NULL,
           'Literal ''None'' / NULL means no promotion applied; source not altered' FROM t
    UNION ALL SELECT 'Non-positive quantity', 'ERROR', COUNT_IF(QUANTITY <= 0),
           ARRAY_SLICE(ARRAY_AGG(IFF(QUANTITY <= 0, TRANSACTION_ID, NULL)),0,20), 'quantity must be > 0' FROM t
    UNION ALL SELECT 'Discount pct outside 0-100', 'ERROR', COUNT_IF(DISCOUNT_PCT < 0 OR DISCOUNT_PCT > 100),
           ARRAY_SLICE(ARRAY_AGG(IFF(DISCOUNT_PCT < 0 OR DISCOUNT_PCT > 100, TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Negative monetary values', 'ERROR',
           COUNT_IF(UNIT_PRICE_INR < 0 OR COST_OF_GOODS_INR < 0 OR SHIPPING_COST_INR < 0 OR MARKETING_COST_INR < 0 OR RETURN_AMOUNT_INR < 0 OR NET_REVENUE_INR < 0),
           ARRAY_SLICE(ARRAY_AGG(IFF(UNIT_PRICE_INR < 0 OR COST_OF_GOODS_INR < 0 OR SHIPPING_COST_INR < 0 OR MARKETING_COST_INR < 0 OR RETURN_AMOUNT_INR < 0 OR NET_REVENUE_INR < 0, TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Future or implausible dates', 'WARNING', COUNT_IF(TRANSACTION_DATE > CURRENT_DATE() OR TRANSACTION_DATE < '2000-01-01'),
           ARRAY_SLICE(ARRAY_AGG(IFF(TRANSACTION_DATE > CURRENT_DATE() OR TRANSACTION_DATE < '2000-01-01', TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Gross revenue <> unit price x quantity', 'WARNING', COUNT_IF(ABS(UNIT_PRICE_INR*QUANTITY - GROSS_REVENUE_INR) > 0.05),
           ARRAY_SLICE(ARRAY_AGG(IFF(ABS(UNIT_PRICE_INR*QUANTITY - GROSS_REVENUE_INR) > 0.05, TRANSACTION_ID, NULL)),0,20), 'tolerance 0.05 INR' FROM t
    UNION ALL SELECT 'Discount amount <> gross x discount pct', 'WARNING', COUNT_IF(ABS(GROSS_REVENUE_INR*DISCOUNT_PCT/100 - DISCOUNT_AMOUNT_INR) > 0.05),
           ARRAY_SLICE(ARRAY_AGG(IFF(ABS(GROSS_REVENUE_INR*DISCOUNT_PCT/100 - DISCOUNT_AMOUNT_INR) > 0.05, TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Revenue <> gross - discount', 'WARNING', COUNT_IF(ABS(GROSS_REVENUE_INR - DISCOUNT_AMOUNT_INR - REVENUE_INR) > 0.05),
           ARRAY_SLICE(ARRAY_AGG(IFF(ABS(GROSS_REVENUE_INR - DISCOUNT_AMOUNT_INR - REVENUE_INR) > 0.05, TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Net revenue <> revenue - returns', 'WARNING', COUNT_IF(ABS(REVENUE_INR - RETURN_AMOUNT_INR - NET_REVENUE_INR) > 0.05),
           ARRAY_SLICE(ARRAY_AGG(IFF(ABS(REVENUE_INR - RETURN_AMOUNT_INR - NET_REVENUE_INR) > 0.05, TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Recorded net profit <> estimated contribution', 'WARNING',
           COUNT_IF(ABS(NET_REVENUE_INR - COST_OF_GOODS_INR - SHIPPING_COST_INR - MARKETING_COST_INR - NET_PROFIT_INR) > 0.05),
           ARRAY_SLICE(ARRAY_AGG(IFF(ABS(NET_REVENUE_INR - COST_OF_GOODS_INR - SHIPPING_COST_INR - MARKETING_COST_INR - NET_PROFIT_INR) > 0.05, TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Return flag inconsistent with return amount', 'WARNING',
           COUNT_IF((RETURNED AND RETURN_AMOUNT_INR = 0) OR (NOT RETURNED AND RETURN_AMOUNT_INR > 0)),
           ARRAY_SLICE(ARRAY_AGG(IFF((RETURNED AND RETURN_AMOUNT_INR = 0) OR (NOT RETURNED AND RETURN_AMOUNT_INR > 0), TRANSACTION_ID, NULL)),0,20), '' FROM t
    UNION ALL SELECT 'Return amount exceeds revenue', 'ERROR', COUNT_IF(RETURN_AMOUNT_INR > REVENUE_INR + 0.05),
           ARRAY_SLICE(ARRAY_AGG(IFF(RETURN_AMOUNT_INR > REVENUE_INR + 0.05, TRANSACTION_ID, NULL)),0,20), '' FROM t
  )
  SELECT :run_id, 'SALES_TRANSACTIONS', c, s, f, (SELECT COUNT(*) FROM t),
         IFF(s = 'INFO', 'INFO', IFF(f = 0, 'PASS', IFF(s = 'ERROR', 'FAIL', 'WARN'))), ids, d
  FROM checks;
  RETURN run_id;
END;
$$;

CALL RUN_DATA_QUALITY_CHECKS();

-- Latest validation report
SELECT CHECK_NAME, SEVERITY, STATUS, FAILED_ROWS, TOTAL_ROWS, SAMPLE_IDS
FROM DATA_QUALITY_RESULTS
WHERE CHECK_RUN_ID = (SELECT CHECK_RUN_ID FROM DATA_QUALITY_RESULTS ORDER BY CHECKED_AT DESC LIMIT 1)
ORDER BY SEVERITY, CHECK_NAME;

-- Reconciliation: file rows vs table rows vs distinct IDs
SELECT (SELECT ROWS_IN_FILE FROM UPLOAD_HISTORY WHERE UPLOAD_ID='SAMPLE_INITIAL_LOAD') AS rows_in_file,
       COUNT(*) AS rows_in_table, COUNT(DISTINCT TRANSACTION_ID) AS distinct_ids
FROM SALES_TRANSACTIONS;
