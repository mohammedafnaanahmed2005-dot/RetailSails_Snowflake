-- 02_table_schema.sql
-- Core tables. IF NOT EXISTS keeps reruns non-destructive.
USE ROLE RETAIL_ANALYST;
USE WAREHOUSE RETAIL_WH;
USE SCHEMA RETAIL_ANALYTICS.SALES;

-- One row per transaction line. No PK enforcement in Snowflake, so duplicates are
-- detected by validation (05_validation_queries.sql) rather than rejected silently.
CREATE TABLE IF NOT EXISTS SALES_TRANSACTIONS (
  TRANSACTION_ID       VARCHAR(50)   NOT NULL,
  TRANSACTION_DATE     DATE          NOT NULL,
  PRODUCT_NAME         VARCHAR(200),
  CATEGORY             VARCHAR(100),
  REGION               VARCHAR(100),
  SALES_CHANNEL        VARCHAR(50),
  CUSTOMER_SEGMENT     VARCHAR(50),
  QUANTITY             NUMBER(10,0),
  UNIT_PRICE_INR       NUMBER(14,2),
  DISCOUNT_PCT         NUMBER(6,2),
  GROSS_REVENUE_INR    NUMBER(16,2),
  DISCOUNT_AMOUNT_INR  NUMBER(16,2),
  REVENUE_INR          NUMBER(16,2),
  COST_OF_GOODS_INR    NUMBER(16,2),
  SHIPPING_COST_INR    NUMBER(16,2),
  MARKETING_COST_INR   NUMBER(16,2),
  RETURNED             BOOLEAN,
  RETURN_AMOUNT_INR    NUMBER(16,2),
  NET_REVENUE_INR      NUMBER(16,2),
  NET_PROFIT_INR       NUMBER(16,2),
  PAYMENT_METHOD       VARCHAR(50),
  PROMOTION_TYPE       VARCHAR(50),
  SOURCE_FILE          VARCHAR(500),
  UPLOAD_ID            VARCHAR(64),
  LOADED_AT            TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS UPLOAD_HISTORY (
  UPLOAD_ID          VARCHAR(64),
  FILE_NAME          VARCHAR(500),
  TARGET_TABLE       VARCHAR(200),
  LOAD_MODE          VARCHAR(20),     -- APPEND / REPLACE / NEW_TABLE / COPY_INTO
  UPLOADED_AT        TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  UPLOADED_BY        VARCHAR(200) DEFAULT CURRENT_USER(),
  ROWS_IN_FILE       NUMBER,
  ROWS_LOADED        NUMBER,
  ROWS_REJECTED      NUMBER,
  STATUS             VARCHAR(20),     -- SUCCESS / PARTIAL / FAILED / REJECTED
  VALIDATION_SUMMARY VARIANT
);

CREATE TABLE IF NOT EXISTS DATA_QUALITY_RESULTS (
  CHECK_RUN_ID   VARCHAR(64),
  CHECKED_AT     TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  TABLE_NAME     VARCHAR(200),
  CHECK_NAME     VARCHAR(200),
  SEVERITY       VARCHAR(20),         -- ERROR / WARNING / INFO
  FAILED_ROWS    NUMBER,
  TOTAL_ROWS     NUMBER,
  STATUS         VARCHAR(10),         -- PASS / FAIL / WARN
  SAMPLE_IDS     ARRAY,
  DETAILS        VARCHAR(2000)
);
